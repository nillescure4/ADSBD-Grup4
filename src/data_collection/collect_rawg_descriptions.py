#!/usr/bin/env python3
"""Collect raw RAWG game-detail JSON for text descriptions.

The game catalogue is read from the games.jsonl manifest generated by
collect_rawg_images.py. Raw API responses are preserved unchanged in the
Landing Zone and a JSONL provenance manifest is written alongside them.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, Iterable

import requests
from requests.adapters import HTTPAdapter
from urllib3.util.retry import Retry

RAWG_BASE = "https://api.rawg.io/api"


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def build_session() -> requests.Session:
    retry = Retry(
        total=6,
        connect=5,
        read=5,
        status=5,
        backoff_factor=1.2,
        status_forcelist=(429, 500, 502, 503, 504),
        allowed_methods=frozenset({"GET"}),
        respect_retry_after_header=True,
    )
    adapter = HTTPAdapter(max_retries=retry, pool_connections=8, pool_maxsize=8)
    session = requests.Session()
    session.mount("https://", adapter)
    session.headers.update({
        "User-Agent": "ADSDB-video-game-project/1.0 (academic, non-commercial)",
        "Accept": "application/json",
    })
    return session


def rawg_get(session: requests.Session, api_key: str, endpoint: str, timeout: int = 45) -> Dict[str, Any]:
    response = session.get(
        f"{RAWG_BASE}{endpoint}",
        params={"key": api_key},
        timeout=timeout,
    )
    response.raise_for_status()
    return response.json()


def iter_games(manifest: Path) -> Iterable[Dict[str, Any]]:
    with manifest.open("r", encoding="utf-8") as f:
        for line_no, line in enumerate(f, start=1):
            if not line.strip():
                continue
            try:
                row = json.loads(line)
            except json.JSONDecodeError as exc:
                print(f"[WARN] invalid JSON at line {line_no}: {exc}", file=sys.stderr)
                continue
            if row.get("source_game_id") is None:
                print(f"[WARN] line {line_no}: missing source_game_id", file=sys.stderr)
                continue
            yield row


def save_json(path: Path, payload: Dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")


def append_jsonl(path: Path, row: Dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as f:
        f.write(json.dumps(row, ensure_ascii=False) + "\n")


def load_manifest_asset_ids(path: Path) -> set[str]:
    ids: set[str] = set()
    if not path.exists():
        return ids
    with path.open("r", encoding="utf-8") as f:
        for line in f:
            if not line.strip():
                continue
            try:
                row = json.loads(line)
            except json.JSONDecodeError:
                continue
            if row.get("asset_id"):
                ids.add(str(row["asset_id"]))
    return ids


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Collect raw RAWG game-detail JSON used as game descriptions."
    )
    parser.add_argument(
        "--games-manifest",
        required=True,
        help="Path to games.jsonl produced by collect_rawg_images.py.",
    )
    parser.add_argument(
        "--output",
        default="data/landing/text_descriptions",
        help="Output directory for raw JSON and the text-source manifest.",
    )
    parser.add_argument("--api-key", default=os.getenv("RAWG_API_KEY"))
    parser.add_argument("--max-games", type=int, default=None, help="Optional limit for testing.")
    parser.add_argument("--delay", type=float, default=0.15, help="Delay between RAWG requests in seconds.")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    if not args.api_key:
        raise SystemExit("Missing RAWG API key. Set RAWG_API_KEY or pass --api-key.")

    games_manifest = Path(args.games_manifest)
    if not games_manifest.exists():
        raise SystemExit(f"Manifest not found: {games_manifest}")

    output_root = Path(args.output)
    details_dir = output_root / "raw_api" / "rawg" / "game_details"
    manifest_path = output_root / "manifests" / "text_sources.jsonl"
    existing_assets = load_manifest_asset_ids(manifest_path)

    session = build_session()
    counters = {
        "games_seen": 0,
        "rawg_details_saved": 0,
        "rawg_details_skipped": 0,
        "manifest_rows_recovered": 0,
        "errors": 0,
    }

    for idx, game in enumerate(iter_games(games_manifest), start=1):
        if args.max_games is not None and idx > args.max_games:
            break

        counters["games_seen"] += 1
        rawg_id = int(game["source_game_id"])
        game_name = game.get("name") or f"rawg_{rawg_id}"
        asset_id = f"rawg:{rawg_id}:game_details"
        detail_path = details_dir / f"{rawg_id}.json"
        print(f"[{counters['games_seen']}] {rawg_id} - {game_name}")

        if detail_path.exists():
            counters["rawg_details_skipped"] += 1
            print("  [SKIP] RAWG details already present")
            if asset_id not in existing_assets:
                append_jsonl(manifest_path, {
                    "asset_id": asset_id,
                    "modality": "text",
                    "text_source_type": "game_description_source",
                    "source": "rawg",
                    "source_game_id": rawg_id,
                    "game_name": game_name,
                    "raw_object_path": str(detail_path.relative_to(output_root)),
                    "expected_text_fields": ["description_raw", "description"],
                    "ingested_at_utc": utc_now(),
                })
                existing_assets.add(asset_id)
                counters["manifest_rows_recovered"] += 1
            continue

        try:
            details = rawg_get(session, args.api_key, f"/games/{rawg_id}")
            save_json(detail_path, details)
            append_jsonl(manifest_path, {
                "asset_id": asset_id,
                "modality": "text",
                "text_source_type": "game_description_source",
                "source": "rawg",
                "source_game_id": rawg_id,
                "game_name": game_name,
                "raw_object_path": str(detail_path.relative_to(output_root)),
                "expected_text_fields": ["description_raw", "description"],
                "ingested_at_utc": utc_now(),
            })
            existing_assets.add(asset_id)
            counters["rawg_details_saved"] += 1
            print("  [OK] RAWG game details")
        except Exception as exc:
            counters["errors"] += 1
            print(f"  [WARN] RAWG details failed: {exc}", file=sys.stderr)

        if args.delay > 0:
            time.sleep(args.delay)

    save_json(output_root / "collection_summary.json", {
        "completed_at_utc": utc_now(),
        "source": "RAWG",
        "games_manifest": str(games_manifest),
        **counters,
    })


if __name__ == "__main__":
    main()
